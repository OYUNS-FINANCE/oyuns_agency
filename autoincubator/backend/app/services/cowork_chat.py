"""Chat with an agent about one idea, streamed (ADR 0006).

The founder's message and a `pending` reply are stored first. The reply is generated by a
task that is not tied to the HTTP request: a client that disconnects (or reloads) does not
cancel it, and the stored message is completed either way. The response only relays what
the task produces, as SSE events: `started`, `delta`*, `reset`, then `completed` or `error`.
"""

