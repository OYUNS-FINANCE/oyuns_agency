import asyncio
import contextlib
import json
import uuid
from collections.abc import AsyncIterator
from dataclasses import dataclass, field
from typing import Any

from pydantic import BaseModel
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker

from app.agents.common.context import render_run_context
from app.agents.common.schemas import RunInput
from app.agents.cowork.chat import cowork_reply
from app.agents.cowork.schemas import CoworkInput, TranscriptLine
from app.core.config import Settings
from app.core.errors import ConflictError
from app.core.logging import get_logger
from app.db.enums import CoworkAgent, CoworkMessageState, CoworkRole
from app.db.models import Run
from app.db.repositories import cowork as cowork_repo
from app.providers.llm.base import LLMOutputError, LLMRefusalError
from app.services import cowork as cowork_service
from app.services import ideas as ideas_service
from app.services.brief_patch import EditableBrief
from app.services.budget import BudgetExhaustedError
from app.services.run_deps import run_deps
